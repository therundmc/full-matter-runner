PAINTINGS = {}


def painting(name, palette, art):
    """Register a painting: its rows read from the text, checked (one width, every character in the legend)."""
    rows = [ln.split()[1] for ln in art.splitlines() if ln[:1].isdigit()]
    assert rows and len(set(len(r) for r in rows)) == 1, (name, sorted(set(len(r) for r in rows)))
    assert not set(''.join(rows)) - set(palette), (name, set(''.join(rows)) - set(palette))
    PAINTINGS[name] = (palette, rows)


def image(name):
    """A painting as an RGBA image ('.' transparent)."""
    palette, rows = PAINTINGS[name]
    im = Image.new('RGBA', (len(rows[0]), len(rows)), (0, 0, 0, 0))
    px = im.load()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if palette[ch] is not None:
                px[x, y] = palette[ch] + (255,)
    return im


def stamp(cv, name, x, y):
    """Paste a painting into a canvas (kit.Cv), its top left corner at panel px (x, y)."""
    im = image(name)
    cv.im.paste(im, (int(x), int(y)), im)


def sheet(path, k=6, ground=(58, 44, 66)):
    """Every painting alone, at k x, on one plain ground: the contact sheet."""
    ims = [image(n) for n in PAINTINGS]
    gap = 8
    w = sum(im.size[0] for im in ims) + gap * (len(ims) + 1)
    h = max(im.size[1] for im in ims) + gap * 2
    out = Image.new('RGB', (w, h), ground)
    x = gap
    for im in ims:
        out.paste(im, (x, gap), im)
        x += im.size[0] + gap
    out.resize((w * k, h * k), Image.NEAREST).save(path)


