#!/usr/bin/env python3
"""The title screen's stills (the poster, and the hit list: the LEVELS page and the screen between levels):

    python3 tools/comic/title.py              the layers the game animates, and their data
    python3 tools/comic/title.py <out-dir>    the same, and the stills and frame strips in <out-dir>

Writes, deterministic:
  assets/sprites/title/   poster_sky.png, poster_city.png, poster_front.png (the poster's three layers, 24 px wider
                          than the sheet each side for the parallax), logo.png, logo_off.png, board_bg.png and
                          board_0.png .. board_4.png (what is pinned to the board, one per number of targets dead):
                          optional sprites (engine/Assets.js), drawn by src/game/ui/title/Poster.js and HitList.js
  src/game/data/titleart.js   where things are in them, for what the game cuts live over them (never edit it by hand)
In <out-dir>: poster.png and board_<n>.png (each picture whole, as a still), their 1920 x 1080 nearest upscales
(*_1080.png), and strip_<name>.png for every run of frames frame_<name>_<i>.png found there (tools/shot.mjs).
The art is in title_art.py; the direction in STYLE.md (The title)."""
import json
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from comic import title_art as art  # noqa: E402
from comic.kit import CYAN, FLUO, INK, PINK, ROOT  # noqa: E402

TITLE_DIR = os.path.join(ROOT, 'assets', 'sprites', 'title')
DATA = os.path.join(ROOT, 'src', 'game', 'data', 'titleart.js')
LAYERS = ['poster_sky', 'poster_city', 'poster_front', 'logo', 'logo_off', 'board_bg', 'options_bg', 'options_things'] + ['board_%d' % n for n in range(len(art.TARGETS) + 1)]


def rnd(v):
    """Numbers to one decimal, through lists and dicts."""
    if isinstance(v, dict):
        return {k: rnd(x) for k, x in v.items()}
    if isinstance(v, (list, tuple)):
        return [rnd(x) for x in v]
    return round(v, 1) if isinstance(v, float) else v


def layers():
    """The stills the game animates. Returns their data."""
    os.makedirs(TITLE_DIR, exist_ok=True)
    for n in os.listdir(TITLE_DIR):                                                          # nothing stale
        if n.endswith('.png') and n[:-4] not in LAYERS:
            os.remove(os.path.join(TITLE_DIR, n))
    sky, signs, ember = art.sky_layer()
    sky.im.save(os.path.join(TITLE_DIR, 'poster_sky.png'))
    art.city_layer(live=True)[0].im.save(os.path.join(TITLE_DIR, 'poster_city.png'))
    art.front_layer().im.save(os.path.join(TITLE_DIR, 'poster_front.png'))
    on, boxes = art.logo()
    on.save(os.path.join(TITLE_DIR, 'logo.png'))
    art.logo(lit=set())[0].save(os.path.join(TITLE_DIR, 'logo_off.png'))
    art.board_bg()[0].im.save(os.path.join(TITLE_DIR, 'board_bg.png'))
    for done in range(len(art.TARGETS) + 1):
        art.board_overlay(done, live=True).im.save(os.path.join(TITLE_DIR, 'board_%d.png' % done))
    art.options_bg().im.save(os.path.join(TITLE_DIR, 'options_bg.png'))
    art.things_sheet().im.save(os.path.join(TITLE_DIR, 'options_things.png'))
    for n in LAYERS:
        with Image.open(os.path.join(TITLE_DIR, n + '.png')) as im:
            assert im.size[0] % 3 == 0 and im.size[1] % 3 == 0, (n, im.size)
    of = lambda who, ink: [pts for i, pts in signs[who] if i == ink]
    cx, cy, h = art.RUNNER_AT
    poster = dict(
        margin=art.MX, glow=list(art.GLOW), building=art.B, windows=art.windows(), roofFlames=art.ROOF_FLAMES, logo=list(art.LOGO_AT), letters=boxes,
        shades=of('cueball', FLUO)[0], scarf=of('lucky', PINK), crest=of('jitters', CYAN)[0], ember=list(ember),
        # his shoulders (the rain breaks on them) and the box of his head (nothing is drawn across it)
        shoulders=[cx - 0.13 * h, cx + 0.13 * h, cy - 0.86 * h], head=[cx - 0.3 * h, cy - 1.14 * h, cx + 0.14 * h, cy - 0.84 * h])
    board = dict(
        card=list(art.CARD), cards=[[t[4][0], t[4][1], t[5]] for t in art.TARGETS], pins=[art.card_pin(t) for t in art.TARGETS],
        crosses=[[[a, b, w0, w1] for a, b, w0, w1 in art.card_cross(t)] for t in art.TARGETS],
        tags=[[art.card_tag(t)[0][0], art.card_tag(t)[0][1], art.card_tag(t)[1]] for t in art.TARGETS],
        photo=list(art.PHOTO), photoPin=art.board_pins(0)[0], matchbook=list(art.MATCHBOOK), matchPin=art.matchbook_pin(),
        flamingo=[pts for ink, pts in art.FLAMINGO if ink != INK], bar=art.bar_cut())
    options = dict(cell=list(art.THING), things=[dict(name=n, at=list(at), lean=deg, slab='#%02x%02x%02x' % ink) for n, at, deg, ink in art.THINGS],
                   reels=art.REELS, screen=list(art.SCREEN))
    with open(DATA, 'w') as f:
        f.write('// GENERATED by tools/comic/title.py from tools/comic/title_art.py: never edit by hand.\n')
        f.write('// Where things are in the title\'s stills (assets/sprites/title/), in their px (3 a title px), for what the game\n')
        f.write('// cuts live over them: ui/title/Poster.js (POSTER), ui/title/HitList.js (BOARD), ui/title/Options.js (OPTIONS).\n')
        f.write('export const POSTER = %s;\n' % json.dumps(rnd(poster)))
        f.write('export const BOARD = %s;\n' % json.dumps(rnd(board)))
        f.write('export const OPTIONS = %s;\n' % json.dumps(rnd(options)))


def stills(out):
    os.makedirs(out, exist_ok=True)
    pics = [('poster', art.poster_art()), ('options', art.options_art())] + [('board_%d' % n, art.board_art(n)) for n in range(len(art.TARGETS) + 1)]
    for name, im in pics:
        im.save(os.path.join(out, name + '.png'))
        im.resize((1920, 1080), Image.NEAREST).save(os.path.join(out, name + '_1080.png'))


def strips(out):
    """strip_<name>.png: the frames frame_<name>_<i>.png taken of the game, at half size, four to a row."""
    runs = {}
    for n in sorted(os.listdir(out)):
        if n.startswith('frame_') and n.endswith('.png'):
            name, i = n[6:-4].rsplit('_', 1)
            runs.setdefault(name, []).append((int(i), n))
    for name, frames in runs.items():
        ims = [Image.open(os.path.join(out, n)).convert('RGB') for _, n in sorted(frames)]
        tw, th, cols = ims[0].size[0] // 2, ims[0].size[1] // 2, 4
        rows = (len(ims) + cols - 1) // cols
        sheet = Image.new('RGB', (cols * (tw + 6) + 6, rows * (th + 6) + 6), INK)
        for i, im in enumerate(ims):
            sheet.paste(im.resize((tw, th), Image.NEAREST), (6 + (i % cols) * (tw + 6), 6 + (i // cols) * (th + 6)))
        sheet.save(os.path.join(out, 'strip_%s.png' % name))


if __name__ == '__main__':
    layers()
    print('title layers in %s, their data in %s' % (TITLE_DIR, DATA))
    if len(sys.argv) > 1:
        stills(sys.argv[1])
        strips(sys.argv[1])
        print('stills and strips in %s' % sys.argv[1])
